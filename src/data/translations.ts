export const getTranslation = (lang: string, key: string): any => {
  const langTranslations = translations[lang as keyof typeof translations] || translations.en
  const keys = key.split('.')
  let value = langTranslations as any

  for (const k of keys) {
    value = value[k]
    if (!value) return key
  }

  return value
}
